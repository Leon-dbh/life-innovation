$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$bad = New-Object System.Collections.Generic.List[string]

$files = Get-ChildItem -Path $root -Recurse -Filter '*.ps1' -File |
  Where-Object { $_.FullName -notmatch '[\\/]\.git[\\/]' }

foreach ($file in $files) {
  $bytes = [System.IO.File]::ReadAllBytes($file.FullName)
  if ($bytes.Length -lt 3 -or $bytes[0] -ne 0xEF -or $bytes[1] -ne 0xBB -or $bytes[2] -ne 0xBF) {
    $bad.Add("$($file.FullName): missing UTF-8 BOM")
  }

  $tokens = $null
  $errors = $null
  [System.Management.Automation.Language.Parser]::ParseFile($file.FullName, [ref]$tokens, [ref]$errors) | Out-Null
  foreach ($parseError in $errors) {
    $bad.Add("$($file.FullName):$($parseError.Extent.StartLineNumber): $($parseError.Message)")
  }
}

if ($bad.Count -gt 0) {
  $bad | ForEach-Object { Write-Error $_ }
  exit 1
}

Write-Host "OK: PowerShell UTF-8 BOM/parser ($($files.Count) files)"

